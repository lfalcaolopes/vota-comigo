const BASE58_CODE = /^[1-9A-HJ-NP-Za-km-z]{6}$/;

function indexCampaignLinks(links: readonly CampaignLink[]) {
  const byCode = new Map<string, CampaignLink>();
  const utmContents = new Set<string>();

  for (const link of links) {
    if (!BASE58_CODE.test(link.code)) {
      throw new Error(`Invalid campaign short code: ${link.code}`);
    }
    if (byCode.has(link.code)) {
      throw new Error(`Duplicate campaign short code: ${link.code}`);
    }
    if (utmContents.has(link.utmContent)) {
      throw new Error(`Duplicate campaign utm_content: ${link.utmContent}`);
    }
    if (
      !link.destinationPath.startsWith("/") ||
      link.destinationPath.startsWith("//") ||
      link.destinationPath.includes("?") ||
      link.destinationPath.includes("#")
    ) {
      throw new Error(`Invalid campaign destination: ${link.destinationPath}`);
    }

    byCode.set(link.code, link);
    utmContents.add(link.utmContent);
  }

  return byCode;
}

const campaignLinksByCode = indexCampaignLinks(campaignLinks);

export function buildCampaignDestination(
  requestUrl: URL,
  code: string,
): URL | null {
  const link = campaignLinksByCode.get(code);
  if (!link) return null;

  const destination = new URL(link.destinationPath, requestUrl.origin);

  for (const [name, value] of requestUrl.searchParams) {
    if (!name.startsWith("utm_")) destination.searchParams.append(name, value);
  }

  destination.searchParams.set("utm_source", link.utmSource);
  destination.searchParams.set("utm_medium", link.utmMedium);
  destination.searchParams.set("utm_campaign", link.utmCampaign);
  destination.searchParams.set("utm_content", link.utmContent);

  return destination;
}
