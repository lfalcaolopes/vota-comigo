// Nao inclui os adicionais mensais por cargo (lideranca, presidencia de
// comissao, suplencia de secretario da Mesa), que sao somados ao teto e nao
// tem serie historica por deputado.
export function limiteMensalCota(siglaUf: string, data: string): number | null {
  const vigencia = vigenciasLimiteCota.find(
    (candidata) =>
      data >= candidata.inicio &&
      (candidata.fim === null || data <= candidata.fim),
  );

  return vigencia?.limitePorUf[siglaUf] ?? null;
}
